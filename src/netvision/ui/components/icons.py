_ICON_CACHE = {}


def get_icon(name: str, size: int = 18, color_normal: Optional[str] = None, color_active: Optional[str] = None) -> QIcon:
    """
    Returns a crisp vector QIcon from the Lucide collection.
    Provides automatic normal and active/selected state pixmaps.
    """
    normal_col = color_normal or COLORS.get("text_secondary", "#8291A3")
    active_col = color_active or COLORS.get("primary", "#22B8CF")
    cache_key = (name, size, normal_col, active_col)

    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    svg_template = LUCIDE_SVGS.get(name)
    if not svg_template:
        return QIcon()

    # Normal state pixmap
    xml_normal = svg_template.replace("{color}", normal_col)
    renderer_n = QSvgRenderer(QByteArray(xml_normal.encode("utf-8")))
    pix_normal = QPixmap(size, size)
    pix_normal.fill(Qt.transparent)
    p_n = QPainter(pix_normal)
    p_n.setRenderHint(QPainter.Antialiasing, True)
    renderer_n.render(p_n)
    p_n.end()

    # Active/Selected state pixmap
    xml_active = svg_template.replace("{color}", active_col)
    renderer_a = QSvgRenderer(QByteArray(xml_active.encode("utf-8")))
    pix_active = QPixmap(size, size)
    pix_active.fill(Qt.transparent)
    p_a = QPainter(pix_active)
    p_a.setRenderHint(QPainter.Antialiasing, True)
    renderer_a.render(p_a)
    p_a.end()

    icon = QIcon()
    icon.addPixmap(pix_normal, QIcon.Normal, QIcon.Off)
    icon.addPixmap(pix_active, QIcon.Normal, QIcon.On)
    icon.addPixmap(pix_active, QIcon.Active, QIcon.Off)
    icon.addPixmap(pix_active, QIcon.Selected, QIcon.Off)

    _ICON_CACHE[cache_key] = icon
    return icon
